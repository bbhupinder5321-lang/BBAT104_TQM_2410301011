    def create_bed_panel(self, parent):
        card = ctk.CTkFrame(
            parent,
            fg_color=self.CARD,
            corner_radius=18,
            border_width=1,
            border_color=self.BORDER
        )
        card.grid(
            row=0,
            column=1,
            padx=(7, 0),
            sticky="nsew"
        )

        header = ctk.CTkFrame(
            card,
            fg_color="transparent"
        )
        header.pack(
            fill="x",
            padx=20,
            pady=(17, 4)
        )

        ctk.CTkLabel(
            header,
            text="Bed capacity",
            text_color=self.TEXT,
            font=ctk.CTkFont(size=15, weight="bold")
        ).pack(anchor="w")

        ctk.CTkLabel(
            header,
            text="Current hospital capacity",
            text_color=self.SECONDARY,
            font=ctk.CTkFont(size=9)
        ).pack(anchor="w", pady=(2, 0))

        total = int(self.metrics.get("total_beds", 0))
        occupied = int(self.metrics.get("occupied_beds", 0))
        available = int(self.metrics.get("available_beds", 0))

        percentage = self.service.get_bed_occupancy_percentage(
            occupied,
            total
        )
        status, status_kind = self.service.get_occupancy_status(
            occupied,
            total
        )

        self.bed_canvas = ctk.CTkCanvas(
            card,
            width=190,
            height=125,
            bg=self.CARD,
            highlightthickness=0
        )
        self.bed_canvas.pack(
            fill="x",
            pady=(8, 0)
        )

        self.draw_bed_ring(percentage)

        stat_row = ctk.CTkFrame(
            card,
            fg_color="transparent"
        )
        stat_row.pack(
            fill="x",
            padx=18,
            pady=(2, 8)
        )

        self.create_small_stat(
            stat_row,
            "OCCUPIED",
            occupied,
            self.GREEN
        )
        self.create_small_stat(
            stat_row,
            "AVAILABLE",
            available,
            self.BLUE
        )
        self.create_small_stat(
            stat_row,
            "TOTAL",
            total,
            self.SECONDARY
        )

        status_colors = {
            "success": (self.GREEN_SOFT, self.GREEN_DARK),
            "warning": (self.AMBER_SOFT, self.AMBER_DARK),
            "danger": (self.RED_SOFT, self.RED_DARK)
        }
        soft, fg = status_colors[status_kind]

        ctk.CTkLabel(
            card,
            text=f"  {status}  ",
            fg_color=soft,
            text_color=fg,
            corner_radius=8,
            font=ctk.CTkFont(size=8, weight="bold")
        ).pack(
            anchor="w",
            padx=18,
            pady=(0, 9)
        )

        wards = self.metrics.get("bed_wards", [])
        if wards:
            ctk.CTkLabel(
                card,
                text="BY WARD",
                text_color=self.MUTED,
                font=ctk.CTkFont(size=7, weight="bold")
            ).pack(
                anchor="w",
                padx=18,
                pady=(0, 4)
            )

            for ward in wards[:3]:
                ward_name = str(ward["ward"])
                ward_total = int(ward["total_beds"] or 0)
                ward_occupied = int(ward["occupied_beds"] or 0)
                ward_ratio = (
                    ward_occupied / ward_total
                    if ward_total
                    else 0
                )

                ward_row = ctk.CTkFrame(
                    card,
                    fg_color="transparent"
                )
                ward_row.pack(
                    fill="x",
                    padx=18,
                    pady=2
                )

                ctk.CTkLabel(
                    ward_row,
                    text=ward_name,
                    text_color=self.SECONDARY,
                    font=ctk.CTkFont(size=7, weight="bold")
                ).pack(side="left")

                ctk.CTkLabel(
                    ward_row,
                    text=f"{ward_occupied}/{ward_total}",
                    text_color=self.TEXT,
                    font=ctk.CTkFont(size=7, weight="bold")
                ).pack(side="right")

                track = ctk.CTkProgressBar(
                    card,
                    height=5,
                    corner_radius=3,
                    fg_color="#E9EEF5",
                    progress_color=self.GREEN if ward_ratio < 0.85 else self.AMBER if ward_ratio < 0.95 else self.RED
                )
                track.pack(
                    fill="x",
                    padx=18,
                    pady=(0, 3)
                )
                track.set(ward_ratio)

        ctk.CTkLabel(
            card,
            text="",
            font=ctk.CTkFont(size=1)
        ).pack(pady=(0, 4))

    def draw_bed_ring(self, percentage):
        canvas = self.bed_canvas

        width = max(canvas.winfo_width(), 190)
        center_x = width / 2
        center_y = 58
        radius = 42

        canvas.delete("all")

        canvas.create_arc(
            center_x - radius,
            center_y - radius,
            center_x + radius,
            center_y + radius,
            start=0,
            extent=359,
            style="arc",
            outline="#E9EEF5",
            width=11
        )

        extent = min(359, 359 * percentage / 100)

        canvas.create_arc(
            center_x - radius,
            center_y - radius,
            center_x + radius,
            center_y + radius,
            start=90,
            extent=-extent,
            style="arc",
            outline=self.GREEN if percentage < 85 else self.AMBER if percentage < 95 else self.RED,
            width=11
        )

        canvas.create_text(
            center_x,
            center_y - 2,
            text=f"{percentage:.1f}%",
            fill=self.TEXT,
            font=("Segoe UI", 18, "bold")
        )

        canvas.create_text(
            center_x,
            center_y + 19,
            text="occupied",
            fill=self.MUTED,
            font=("Segoe UI", 8)
        )

