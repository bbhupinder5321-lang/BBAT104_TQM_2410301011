    def get_refresh_text(self):
        return (
            "Live SQLite data • refreshed "
            + datetime.now().strftime("%H:%M:%S")
        )

    def refresh_dashboard(self):
        if self.refresh_button is not None:
            self.refresh_button.configure(
                state="disabled",
                text="Refreshing..."
            )

        self.update_idletasks()

        try:
            self.load_metrics()
            self.rebuild_dynamic_sections()

        finally:
            if self.refresh_button is not None:
                self.refresh_button.configure(
                    state="normal",
                    text="↻  Refresh"
                )

    def rebuild_dynamic_sections(self):
        # Recreate the scrollable content so every live metric,
        # queue row and capacity visual stays internally consistent.
        for widget in self.main.winfo_children():
            widget.destroy()

        self.create_header()
        self.create_kpi_row()
        self.create_operational_row()
        self.create_capacity_and_quality_row()
        self.create_quick_actions()
        self.create_footer()

