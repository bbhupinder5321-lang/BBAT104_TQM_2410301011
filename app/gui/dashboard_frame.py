    def render_queue(self):
        for widget in self.queue_frame.winfo_children():
            widget.destroy()

        queue = self.metrics.get("queue", [])

        if not queue:
            empty = ctk.CTkFrame(
                self.queue_frame,
                fg_color=self.CARD_SOFT,
                corner_radius=12
            )
            empty.pack(fill="x", padx=6, pady=6)

            ctk.CTkLabel(
                empty,
                text="No appointments are scheduled for today.",
                text_color=self.SECONDARY,
                font=ctk.CTkFont(size=10)
            ).pack(pady=18)

            return

        columns = [
            ("TIME", 0.14),
            ("PATIENT", 0.28),
            ("DOCTOR", 0.28),
            ("STATUS", 0.20)
        ]

        header = ctk.CTkFrame(
            self.queue_frame,
            fg_color="#F8FAFC",
            corner_radius=8
        )
        header.pack(fill="x", padx=6, pady=(0, 3))

        for label, rel in columns:
            ctk.CTkLabel(
                header,
                text=label,
                text_color=self.MUTED,
                font=ctk.CTkFont(size=7, weight="bold")
            ).place(
                relx=sum(x[1] for x in columns[:columns.index((label, rel))]),
                rely=0.5,
                anchor="w"
            )

        for item in queue:
            self.create_queue_row(item)

    def create_queue_row(self, item):
        row = ctk.CTkFrame(
            self.queue_frame,
            fg_color=self.CARD_SOFT,
            corner_radius=9,
            border_width=1,
            border_color="#EDF1F5"
        )
        row.pack(
            fill="x",
            padx=6,
            pady=2
        )

        time_text = str(item["appointment_time"])[:5]
        patient = str(item["patient_name"])
        doctor = str(item["doctor_name"])
        status = str(item["status"])

        if len(patient) > 24:
            patient = patient[:23] + "…"

        if len(doctor) > 22:
            doctor = doctor[:21] + "…"

        status_map = {
            "Scheduled": (self.AMBER_SOFT, self.AMBER_DARK),
            "Checked In": (self.CYAN_SOFT, self.CYAN),
            "Completed": (self.GREEN_SOFT, self.GREEN_DARK),
            "Cancelled": (self.RED_SOFT, self.RED_DARK)
        }
        soft, fg = status_map.get(
            status,
            (self.BLUE_SOFT, self.BLUE_DARK)
        )

        values = [
            (time_text, self.TEXT, 0.03),
            (patient, self.TEXT, 0.17),
            (doctor, self.SECONDARY, 0.45)
        ]

        for text, color, relx in values:
            ctk.CTkLabel(
                row,
                text=text,
                text_color=color,
                font=ctk.CTkFont(size=8, weight="bold" if relx == 0.03 else "normal")
            ).place(
                relx=relx,
                rely=0.5,
                anchor="w"
            )

        ctk.CTkLabel(
            row,
            text=f"  {status}  ",
            fg_color=soft,
            text_color=fg,
            corner_radius=7,
            font=ctk.CTkFont(size=7, weight="bold")
        ).place(
            relx=0.74,
            rely=0.5,
            anchor="w"
        )

        ctk.CTkLabel(
            row,
            text=f"#{item['appointment_id']}",
            text_color=self.MUTED,
            font=ctk.CTkFont(size=7)
        ).place(
            relx=0.96,
            rely=0.5,
            anchor="e"
        )

        row.configure(height=35)
        row.pack_propagate(False)

